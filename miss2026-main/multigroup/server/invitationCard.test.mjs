import test from "node:test";
import assert from "node:assert/strict";
import {invitationKey,sealInvitation,openInvitation} from "./invitationCard.mjs";
import {createGroup} from "./registration.mjs";
import {manageGroup,invitationView,ownerView,acceptInvitation,removePlayer} from "./management.mjs";
import {resetContest} from "./reset.mjs";
const key=invitationKey("test secret"),groupId="g",ownerUid="u",password="test-private-password";
const binding={groupId,ownerUid};
const wrap=registration=>({rooms:{miss2027:{gameId:"g1",tour:1,votesOpen:false}},events:{miss2027:{registration}}});
test("card encryption is authenticated and bound to exactly the owner and group",()=>{
 const card=sealInvitation(key,{...binding,password});
 assert.equal(JSON.stringify(card).includes(password),false);
 const plain=openInvitation(key,card,binding);assert.equal(plain.password,password);
 assert.equal(openInvitation(key,card,{...binding,ownerUid:"other"}),null);
 assert.equal(openInvitation(invitationKey("other"),card,binding),null);
 assert.equal(openInvitation(key,{...card,tag:"00".repeat(16)},binding),null);
 assert.equal(JSON.stringify(card).includes(plain.token),false);
});
test("stable invitation survives repeated sharing, legacy links and game reset; revoke invalidates both",()=>{
 const card=sealInvitation(key,{...binding,password}),nextCard=sealInvitation(key,{...binding,password});
 let root=wrap(createGroup({}, {uid:ownerUid,id:groupId,name:"Famille",pseudo:"Owner",secret:"hash",now:1}).state);
 const legacy="a".repeat(64);
 root=manageGroup(root,{uid:ownerUid,action:"invite",digest:legacy}).state;
 assert.equal(manageGroup(root,{uid:"other",action:"publish_invitation",verifiedSecret:"hash",card}).code,"owner_required");
 assert.equal(manageGroup(root,{uid:ownerUid,action:"publish_invitation",verifiedSecret:"bad",card}).code,"invalid_password");
 root=manageGroup(root,{uid:ownerUid,action:"publish_invitation",verifiedSecret:"hash",card}).state;
 assert.equal(manageGroup(root,{uid:ownerUid,action:"publish_invitation",verifiedSecret:"hash",card:nextCard}).state,root);
 assert.equal(invitationView(root,legacy).result.group.id,groupId);
 assert.equal(invitationView(root,card.digest).result.group.id,groupId);
 assert.equal(invitationView(root,nextCard.digest).code,"unavailable");
 assert.equal(JSON.stringify(ownerView(root,ownerUid)).includes(card.data),false);
 root=acceptInvitation(root,{uid:"friend",digest:card.digest,pseudo:"Friend",now:2}).state;
 assert.equal(ownerView(root,ownerUid).result.group.memberCount,2);
 root=resetContest(root,"game","g2").state;
 assert.equal(invitationView(root,card.digest).result.group.id,groupId);
 const removed=removePlayer(root,{targetUid:ownerUid,groupId,gameId:"g2",confirmed:true,now:3}).state;
 assert.equal(invitationView(removed,card.digest).code,"unavailable");
 const revoked=manageGroup(root,{uid:ownerUid,action:"revoke"}).state;
 assert.equal(invitationView(revoked,card.digest).code,"unavailable");assert.equal(invitationView(revoked,legacy).code,"unavailable");
});
test("new groups have a ready card; 30-player cap and lock remain enforced",()=>{
 const card=sealInvitation(key,{...binding,password});
 let root=wrap(createGroup({}, {uid:ownerUid,id:groupId,name:"Famille",pseudo:"Owner",secret:"hash",now:1,inviteCard:card}).state);
 for(let i=1;i<30;i++)root=acceptInvitation(root,{uid:"u"+i,digest:card.digest,pseudo:"Friend "+i,now:2}).state;
 assert.equal(ownerView(root,ownerUid).result.group.memberCount,30);
 assert.equal(acceptInvitation(root,{uid:"last",digest:card.digest,pseudo:"Last",now:2}).code,"group_full");
 root.rooms.miss2027.registrationLocked=true;
 assert.equal(invitationView(root,card.digest).code,"unavailable");
});
